import crypto from "node:crypto";

const {
  SHOPIFY_API_KEY,
  SHOPIFY_API_SECRET,

  SHOPIFY_PARTNER_ORG_ID,
  SHOPIFY_PARTNER_ACCESS_TOKEN,
  SHOPIFY_APP_ID,

  SHOPIFY_APP_EVENTS_API_VERSION = "2026-07",
  SHOPIFY_PARTNER_API_VERSION = "2026-07",
} = process.env;

const SHOP_ID = "gid://shopify/Shop/101762498853";
const EVENT_HANDLE = "bronze-top-up-free";

function requireEnv(name, value) {
  if (!value) {
    throw new Error(`Missing ${name}`);
  }
  return value;
}

requireEnv("SHOPIFY_API_KEY", SHOPIFY_API_KEY);
requireEnv("SHOPIFY_API_SECRET", SHOPIFY_API_SECRET);
requireEnv("SHOPIFY_PARTNER_ORG_ID", SHOPIFY_PARTNER_ORG_ID);
requireEnv(
  "SHOPIFY_PARTNER_ACCESS_TOKEN",
  SHOPIFY_PARTNER_ACCESS_TOKEN,
);
requireEnv("SHOPIFY_APP_ID", SHOPIFY_APP_ID);

//
// 1. Shopify App Events bearer token
//
async function getAppEventsAccessToken() {
  const response = await fetch(
    "https://api.shopify.com/auth/access_token",
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        client_id: SHOPIFY_API_KEY,
        client_secret: SHOPIFY_API_SECRET,
        grant_type: "client_credentials",
      }),
    },
  );

  const body = await response.json();

  if (!response.ok) {
    throw new Error(
      `App Events authentication failed (${response.status}): ${JSON.stringify(
        body,
      )}`,
    );
  }

  return body.access_token;
}

//
// 2. Read the current Shopify meter from Partner API
//
async function getMeter(handle) {
  const endpoint =
    `https://partners.shopify.com/` +
    `${SHOPIFY_PARTNER_ORG_ID}/api/` +
    `${SHOPIFY_PARTNER_API_VERSION}/graphql.json`;

  const query = `
    query ActiveSubscription($appId: ID!, $shopId: ID!) {
      activeSubscription(appId: $appId, shopId: $shopId) {
        billingPeriod
        currentBillingCycle {
          startTime
          endTime
        }
        items {
          handle
          usage {
            quantity
            cost {
              amount
              currencyCode
            }
          }
        }
      }
    }
  `;

  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Shopify-Access-Token":
        SHOPIFY_PARTNER_ACCESS_TOKEN,
    },
    body: JSON.stringify({
      query,
      variables: {
        appId: SHOPIFY_APP_ID,
        shopId: SHOP_ID,
      },
    }),
  });

  const body = await response.json();

  if (!response.ok || body.errors) {
    throw new Error(
      `Partner API failed: ${JSON.stringify(body, null, 2)}`,
    );
  }

  const subscription = body.data?.activeSubscription;

  if (!subscription) {
    throw new Error("No active Shopify subscription.");
  }

  const meter = subscription.items.find(
    (item) => item.handle === handle,
  );

  if (!meter) {
    throw new Error(
      `Meter "${handle}" is not present on activeSubscription.`,
    );
  }

  return {
    billingPeriod: subscription.billingPeriod,
    cycle: subscription.currentBillingCycle,
    handle: meter.handle,
    quantity: Number(meter.usage?.quantity ?? 0),
    costAmount: meter.usage?.cost?.amount ?? null,
    costCurrency:
      meter.usage?.cost?.currencyCode ?? null,
  };
}

//
// 3. Send ONE billing App Event
//
async function sendBillingEvent({
  accessToken,
  idempotencyKey,
}) {
  const endpoint =
    `https://api.shopify.com/app/` +
    `${SHOPIFY_APP_EVENTS_API_VERSION}/events`;

  const payload = {
    shop_id: SHOP_ID,
    event_handle: EVENT_HANDLE,
    timestamp: new Date().toISOString(),

    // THIS IS GENERATED BY MODA.
    idempotency_key: idempotencyKey,

    attributes: {
      value: 1,
      purchase: "hell",
    },
  };

  console.log("\nAPP EVENT REQUEST");
  console.log("=================");
  console.log(JSON.stringify(payload, null, 2));

  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${accessToken}`,
    },
    body: JSON.stringify(payload),
  });

  const body = await response.json().catch(() => null);

  console.log("\nAPP EVENT RESPONSE");
  console.log("==================");
  console.log("HTTP:", response.status);
  console.log(
    "Idempotent-Replay:",
    response.headers.get("Idempotent-Replay"),
  );
  console.log(JSON.stringify(body, null, 2));

  if (!response.ok) {
    throw new Error(
      `App Event submission failed: HTTP ${response.status}`,
    );
  }
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

//
// Main
//
const before = await getMeter(EVENT_HANDLE);

console.log("\nBEFORE");
console.log("======");
console.log(JSON.stringify(before, null, 2));

//
// This is the GUID we create.
//
// Shopify does NOT give this to us.
//
const guid = crypto.randomUUID();

//
// Keep it <= 64 characters.
// 4 + 36 = 40 characters.
//
const shopifyIdempotencyKey = `rcp_${guid}`;

console.log("\nMODA-GENERATED IDENTIFIERS");
console.log("==========================");
console.log("GUID:", guid);
console.log(
  "Shopify idempotency key:",
  shopifyIdempotencyKey,
);

const accessToken = await getAppEventsAccessToken();

await sendBillingEvent({
  accessToken,
  idempotencyKey: shopifyIdempotencyKey,
});

//
// Shopify billing is asynchronous.
//
// Poll Partner API to see when quantity changes.
//
console.log("\nWAITING FOR SHOPIFY BILLING PROCESSING...");
console.log("=========================================");

let after = null;

for (let attempt = 1; attempt <= 12; attempt++) {
  await sleep(5000);

  const current = await getMeter(EVENT_HANDLE);

  console.log(
    `Attempt ${attempt}: quantity=${current.quantity}, cost=${current.costAmount} ${current.costCurrency ?? ""}`,
  );

  if (current.quantity !== before.quantity) {
    after = current;
    break;
  }
}

console.log("\nFINAL RESULT");
console.log("============");

if (!after) {
  console.log(
    "No meter change observed within 60 seconds.",
  );
  console.log(
    "Check Shopify Dev Dashboard -> Logs -> App Billing Event.",
  );
  process.exit(2);
}

console.log("BEFORE:");
console.log(JSON.stringify(before, null, 2));

console.log("\nAFTER:");
console.log(JSON.stringify(after, null, 2));

console.log("\nDELTA:");
console.log({
  quantity:
    after.quantity - before.quantity,
  cost:
    Number(after.costAmount ?? 0) -
    Number(before.costAmount ?? 0),
});

console.log("\nIDENTIFIER TO STORE IN MODA:");
console.log({
  guid,
  shopifyIdempotencyKey,
});
