/** Durable setup history is separate from Shopify's observed active placement. */
export type CartConsentSetupPhase = "never" | "started" | "active" | "restoring" | "unknown";

export type ThemeActivationEvidence = Readonly<{
  placement: "non_plus_cart" | "plus_checkout" | "unknown";
  publishedThemeAvailable: boolean | null;
  cartTemplateSupported: boolean | null;
  blockEnabledInPublishedTheme: boolean | null;
}>;

export type ThemeActivationStatus =
  | "active"
  | "inactive"
  | "unsupported"
  | "unavailable"
  | "unverified";

export function getCartConsentThemeActivationStatus(
  evidence: ThemeActivationEvidence,
): ThemeActivationStatus {
  if (evidence.placement === "plus_checkout") return "unsupported";
  if (evidence.publishedThemeAvailable === false) return "unavailable";
  if (evidence.cartTemplateSupported === false) return "unsupported";
  if (
    evidence.placement !== "non_plus_cart" ||
    evidence.publishedThemeAvailable !== true ||
    evidence.cartTemplateSupported !== true ||
    typeof evidence.blockEnabledInPublishedTheme !== "boolean"
  ) {
    return "unverified";
  }
  return evidence.blockEnabledInPublishedTheme ? "active" : "inactive";
}

export type PlusCheckoutActivationEvidence = Readonly<{
  placement: "non_plus_cart" | "plus_checkout" | "unknown";
  extensionVerified: boolean | null;
}>;

/**
 * Status of the Plus checkout consent extension placement. The cart App Block
 * is the only placement on non-Plus plans, so Plus checkout is `unsupported`
 * there; without positive verification evidence the status stays truthful
 * (`unverified`/`unavailable`) rather than inventing an enabled badge.
 */
export function getPlusCheckoutConsentActivationStatus(
  evidence: PlusCheckoutActivationEvidence,
): ThemeActivationStatus {
  if (evidence.placement === "non_plus_cart") return "unsupported";
  if (evidence.placement !== "plus_checkout") return "unavailable";
  if (evidence.extensionVerified === true) return "active";
  return "unverified";
}

export type CartTemplateEvidence = Readonly<{
  cartTemplateSupported: boolean | null;
  blockEnabledInPublishedTheme: boolean | null;
}>;

/**
 * Shopify writes its published App Block reference using the app name, block
 * handle and a Shopify-generated UUID. That UUID is NOT guaranteed to equal
 * the `uid` in shopify.extension.toml. Match the complete Moda block identity
 * instead of relying on that configuration UID or a loose substring search.
 *
 * The app namespace and block handle must match exactly; only the generated
 * UUID can vary between registered extensions.
 */
const MODA_CART_CONSENT_BLOCK_TYPE =
  /^shopify:\/\/apps\/moda-interact\/blocks\/cart-consent\/[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i;

function isModaCartConsentBlockType(type: unknown): boolean {
  return typeof type === "string" && MODA_CART_CONSENT_BLOCK_TYPE.test(type);
}

/**
 * Derives App Block evidence from a published theme's `templates/cart.json`
 * body. Missing, unreadable or malformed JSON is insufficient evidence of
 * an incompatible theme: verification remains unknown. Only Moda's own
 * `cart-consent` block counts, and blocks under a disabled ancestor section
 * are not treated as enabled.
 */
export type CartConsentBlockPresence = "absent" | "disabled" | "enabled" | "duplicate" | "unknown";

/**
 * Read-only inspection of the published cart template, including disabled
 * blocks/sections. An unavailable template can never be treated as absent.
 * This is not visibility into unsaved Shopify theme-editor changes.
 */
export type CartConsentTemplateInspection = Readonly<{
  presence: CartConsentBlockPresence;
  outcome: "missing_template" | "unterminated_header" | "invalid_json" | "missing_sections" | "parsed";
  generatedHeader: boolean;
  matchingBlocks: number;
  candidateBlocks: number;
}>;

/**
 * Shopify's theme-file API can prepend an autogenerated block-comment header
 * to JSON templates. Strip only that leading header, never JSON string content
 * or arbitrary inline comments. Invalid JSON remains unverified.
 */
export function inspectCartConsentTemplate(content: string | null): CartConsentTemplateInspection {
  const unknown = (outcome: Exclude<CartConsentTemplateInspection["outcome"], "parsed">,
    generatedHeader = false): CartConsentTemplateInspection => ({
    presence: "unknown", outcome, generatedHeader, matchingBlocks: 0, candidateBlocks: 0,
  });
  if (content === null) return unknown("missing_template");
  let json = content.replace(/^\uFEFF/, "").trimStart();
  let generatedHeader = false;
  if (json.startsWith("/*")) {
    const end = json.indexOf("*/", 2);
    if (end < 0) return unknown("unterminated_header");
    json = json.slice(end + 2).trimStart();
    generatedHeader = true;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(json);
  } catch {
    return unknown("invalid_json", generatedHeader);
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    return unknown("missing_sections", generatedHeader);
  }
  const sections = (parsed as Record<string, unknown>).sections;
  if (!sections || typeof sections !== "object" || Array.isArray(sections)) {
    return unknown("missing_sections", generatedHeader);
  }
  let matchingBlocks = 0;
  let enabled = 0;
  let candidateBlocks = 0;
  const visit = (node: unknown, ancestorDisabled: boolean): void => {
    if (!node || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const item of node) visit(item, ancestorDisabled);
      return;
    }
    const record = node as Record<string, unknown>;
    const disabled = ancestorDisabled || record.disabled === true;
    if (typeof record.type === "string" && record.type.includes("/blocks/cart-consent/")) {
      candidateBlocks += 1;
    }
    if (isModaCartConsentBlockType(record.type)) {
      matchingBlocks += 1;
      if (!disabled) enabled += 1;
      return;
    }
    for (const value of Object.values(record)) visit(value, disabled);
  };
  visit(sections, false);
  const presence: CartConsentBlockPresence = matchingBlocks > 1 ? "duplicate"
    : matchingBlocks === 0 ? "absent"
      : enabled > 0 ? "enabled" : "disabled";
  return { presence, outcome: "parsed", generatedHeader, matchingBlocks, candidateBlocks };
}

export function inspectCartConsentBlockPresence(content: string | null): CartConsentBlockPresence {
  return inspectCartConsentTemplate(content).presence;
}

export function deriveCartTemplateEvidence(
  cartTemplateContent: string | null,
): CartTemplateEvidence {
  const presence = inspectCartConsentBlockPresence(cartTemplateContent);
  if (presence === "unknown") {
    return { cartTemplateSupported: null, blockEnabledInPublishedTheme: null };
  }
  return {
    cartTemplateSupported: true,
    blockEnabledInPublishedTheme: presence === "enabled" || presence === "duplicate",
  };
}

export const PLUS_CHECKOUT_EXTENSION_HANDLE = "moda-whatsapp-checkout-consent";
export const PLUS_CHECKOUT_EXTENSION_TARGET =
  "purchase.checkout.contact.render-after";

/**
 * Classifies the read-only App Bridge `shopify.app.extensions()` result as
 * published-placement evidence for the Plus checkout consent extension.
 *
 * - entry with our handle, `ui_extension` type and a published activation at
 *   the contact target => `active`;
 * - successfully queried list without our handle at all => `inactive`;
 * - our handle present but without a verifiable published activation at the
 *   required target (or a malformed list) => `unverified`.
 *
 * This is placement evidence only; it never proves a shopper session or
 * attribute write (S004 owns those semantics).
 */
export function matchPlusCheckoutExtensionEvidence(
  extensions: unknown,
): "active" | "inactive" | "unverified" {
  if (!Array.isArray(extensions)) return "unverified";
  let sawHandle = false;
  for (const entry of extensions) {
    if (!entry || typeof entry !== "object") continue;
    const record = entry as Record<string, unknown>;
    const handle = record.handle ?? record.name;
    if (handle !== PLUS_CHECKOUT_EXTENSION_HANDLE) continue;
    sawHandle = true;
    if (record.type !== "ui_extension") continue;
    const activations: unknown[] = [];
    for (const key of ["activations", "extensionPoints", "targets"]) {
      const value = record[key];
      if (Array.isArray(value)) activations.push(...value);
    }
    for (const activation of activations) {
      if (!activation || typeof activation !== "object") continue;
      const point = activation as Record<string, unknown>;
      const target = point.target ?? point.name;
      if (target !== PLUS_CHECKOUT_EXTENSION_TARGET) continue;
      if (point.published === false || point.draft === true) continue;
      return "active";
    }
  }
  return sawHandle ? "unverified" : "inactive";
}

/** Read-only, published-theme App Bridge evidence for the drawer App Embed. */
export function matchCartDrawerEmbedEvidence(extensions: unknown):
  "active" | "inactive" | "unverified" {
  if (!Array.isArray(extensions)) return "unverified";
  let found = false;
  for (const entry of extensions) {
    if (!entry || typeof entry !== "object") continue;
    const extension = entry as Record<string, unknown>;
    // App Bridge scopes extensions() to the current app. Shopify can report
    // a generic top-level handle ("theme-app-extension"); the nested handle,
    // target and published status identify the specific drawer App Embed.
    if (extension.type !== "theme_app_extension" || !Array.isArray(extension.activations)) continue;
    for (const activation of extension.activations) {
      if (!activation || typeof activation !== "object") continue;
      const block = activation as Record<string, unknown>;
      if (block.handle !== "cart-drawer-consent" || block.target !== "body") continue;
      found = true;
      if (block.status === "active") return "active";
    }
  }
  return found ? "inactive" : "unverified";
}
